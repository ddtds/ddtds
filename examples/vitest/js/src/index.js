/**
 * Adds two numbers.
 *
 * ```js run
 * import { add } from "@ddtds/example-js";
 *
 * expect(add(2, 3)).toBe(5);
 * ```
 *
 * Negative numbers work too:
 *
 * ```js run
 * import { add } from "@ddtds/example-js";
 *
 * expect(add(-2, 1)).toBe(-1);
 * ```
 */
export function add(a, b) {
  return a + b;
}
